import {test} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp} from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {fogEffect} from '../modules/effects/fog/src/model';
import {Projects} from '../core/project/service';
import {Files} from '../adapters/storage-files/project';
import {validateEffectDefinition} from '../adapters/validation-ajv/effect';
const defaults=()=>Object.fromEntries(fogEffect.settings.map(s=>[s.id,s.default]));
test('Fog is deterministic, periodic, independent of seek order and leaves saved values untouched',()=>{
  const values=defaults(),before=structuredClone(values);
  const frame=fogEffect.evaluate(values,6);fogEffect.evaluate(values,12);fogEffect.evaluate(values,0);
  assert.deepEqual(fogEffect.evaluate(values,6),frame);assert.deepEqual(values,before);
  assert.deepEqual(fogEffect.evaluate(values,30),frame);
  assert.notDeepEqual(frame,fogEffect.evaluate({...values,seed:43},6));
  assert.deepEqual(fogEffect.evaluate({...values,speed:0},6),fogEffect.evaluate({...values,speed:0},99));
  assert.deepEqual(fogEffect.evaluate({...values,density:0},6),[]);
  assert.deepEqual(fogEffect.evaluate({...values,opacity:0},6),[]);
  assert.ok(JSON.stringify(fogEffect.evaluate({...values,loop:0,edge:-8,seed:NaN},Infinity)).length>100);
});
test('Fog options and integer bounds validate; duplicated objects and folder roundtrip stay independent',async()=>{
  const {evaluate,editor,...definition}=fogEffect;validateEffectDefinition(definition);
  const invalid=structuredClone(definition);invalid.settings.find(s=>s.id==='shape')!.default='invalid';
  assert.throws(()=>validateEffectDefinition(invalid));
  const model=new Projects(()=>[fogEffect]);model.dispatch({type:'add',effect:'fog'});
  const first=model.snapshot().selected!;model.dispatch({type:'duplicate',id:first});const second=model.snapshot().selected!;
  model.dispatch({type:'set',id:second,key:'color',value:'#ff7744'});
  model.dispatch({type:'set',id:second,key:'shape',value:'rounded'});
  assert.equal(model.snapshot().project.objects[0].settings.color,'#7896bf');
  assert.throws(()=>model.dispatch({type:'set',id:first,key:'seed',value:1.5}));
  assert.throws(()=>model.dispatch({type:'set',id:first,key:'shape',value:'invalid'}));
  model.dispatch({type:'undo'});assert.equal(model.snapshot().project.objects[1].settings.shape,'ellipse');model.dispatch({type:'redo'});
  const dir=await mkdtemp(path.join(os.tmpdir(),'alert-fog-')),files=new Files(),project=model.snapshot().project;
  await files.save(dir,project);assert.deepEqual(await files.open(dir),project);
});
